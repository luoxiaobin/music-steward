def _zh_hant(s: str) -> str:
    return _conv().convert(s)


@lru_cache(maxsize=1)
def _conv():
    from opencc import OpenCC
    return OpenCC("s2twp")      # Taiwan phrasing: 文件夹 → 資料夾, 设置 → 設定, 搜索 → 搜尋


@lru_cache(maxsize=8)
def dictionary(lang: str) -> dict[str, str]:
    """English text/pattern -> translation for `lang` (empty for English)."""
    col = {"zh-Hans": 1, "zh-Hant": 1, "fr-CA": 2, "es-US": 3}.get(lang)
    if col is None:
        return {}
    out = {}
    for row in TABLE:
        t = row[col]
        if lang == "zh-Hant":
            # convert only the text between {placeholders}
            import re
            t = "".join(p if p.startswith("{") else _zh_hant(p) for p in re.split(r"(\{\w+\})", t))
        out[row[0]] = t
    return out
